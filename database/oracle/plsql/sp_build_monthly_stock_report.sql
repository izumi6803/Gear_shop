CREATE TABLE STOCK_MONTHLY_REPORT (
    PERIOD_YM      CHAR(6)      NOT NULL,   -- yyyyMM
    PRODUCT_CODE   VARCHAR2(32) NOT NULL,
    PRODUCT_NAME   VARCHAR2(200),
    WAREHOUSE_CODE VARCHAR2(16) NOT NULL,
    OPENING_QTY    NUMBER(12)   DEFAULT 0 NOT NULL,
    RECEIPT_QTY    NUMBER(12)   DEFAULT 0 NOT NULL,
    ISSUE_QTY      NUMBER(12)   DEFAULT 0 NOT NULL,
    CLOSING_QTY    NUMBER(12)   DEFAULT 0 NOT NULL,
    GENERATED_AT   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_STOCK_MONTHLY_REPORT PRIMARY KEY (PERIOD_YM, PRODUCT_CODE, WAREHOUSE_CODE)
);

CREATE INDEX IX_STOCK_MONTHLY_PRODUCT ON STOCK_MONTHLY_REPORT (PRODUCT_CODE, PERIOD_YM);

-- View cho Crystal Report (join tên hàng + tên kho, đã format sẵn cho reports)
CREATE OR REPLACE VIEW V_STOCK_MONTHLY AS
SELECT  R.PERIOD_YM,
        R.PRODUCT_CODE,
        R.PRODUCT_NAME,
        R.WAREHOUSE_CODE,
        R.OPENING_QTY,
        R.RECEIPT_QTY,
        R.ISSUE_QTY,
        R.CLOSING_QTY,
        R.OPENING_QTY + R.RECEIPT_QTY - R.ISSUE_QTY AS RECALC_CLOSING_QTY,
        TO_CHAR(R.GENERATED_AT, 'YYYY-MM-DD HH24:MI:SS') AS GENERATED_AT_TEXT
FROM    STOCK_MONTHLY_REPORT R;

CREATE OR REPLACE PROCEDURE SP_BUILD_MONTHLY_STOCK_REPORT (
    P_PERIOD_YM IN VARCHAR2
) AS
    V_START_DATE DATE;
    V_END_DATE   DATE;
    V_PREV_YM    CHAR(6);
BEGIN
    IF P_PERIOD_YM IS NULL OR NOT REGEXP_LIKE(P_PERIOD_YM, '^[0-9]{6}$') THEN
        RAISE_APPLICATION_ERROR(-20001, 'P_PERIOD_YM phải có định dạng yyyyMM.');
    END IF;

    V_START_DATE := TO_DATE(P_PERIOD_YM || '01', 'YYYYMMDD');
    V_END_DATE   := ADD_MONTHS(V_START_DATE, 1);
    V_PREV_YM    := TO_CHAR(ADD_MONTHS(V_START_DATE, -1), 'YYYYMM');

    DELETE FROM STOCK_MONTHLY_REPORT WHERE PERIOD_YM = P_PERIOD_YM;

    -- Nguồn dữ liệu: STOCK_MOVEMENT (append-only ledger) đổ về Oracle qua job ETL.
    INSERT INTO STOCK_MONTHLY_REPORT (
        PERIOD_YM, PRODUCT_CODE, PRODUCT_NAME, WAREHOUSE_CODE,
        OPENING_QTY, RECEIPT_QTY, ISSUE_QTY, CLOSING_QTY
    )
    WITH MOVEMENTS AS (
        SELECT  M.PRODUCT_CODE,
                MAX(M.PRODUCT_NAME) AS PRODUCT_NAME,
                M.WAREHOUSE_CODE,
                SUM(CASE WHEN M.OCCURRED_AT <  V_START_DATE THEN M.QUANTITY ELSE 0 END) AS OPENING_QTY,
                SUM(CASE WHEN M.OCCURRED_AT >= V_START_DATE
                          AND M.OCCURRED_AT <  V_END_DATE
                          AND M.QUANTITY > 0 THEN M.QUANTITY ELSE 0 END) AS RECEIPT_QTY,
                SUM(CASE WHEN M.OCCURRED_AT >= V_START_DATE
                          AND M.OCCURRED_AT <  V_END_DATE
                          AND M.QUANTITY < 0 THEN -M.QUANTITY ELSE 0 END) AS ISSUE_QTY
        FROM    STOCK_MOVEMENT M
        WHERE   M.OCCURRED_AT < V_END_DATE
        GROUP BY M.PRODUCT_CODE, M.WAREHOUSE_CODE
    )
    SELECT  P_PERIOD_YM,
            PRODUCT_CODE,
            PRODUCT_NAME,
            WAREHOUSE_CODE,
            OPENING_QTY,
            RECEIPT_QTY,
            ISSUE_QTY,
            OPENING_QTY + RECEIPT_QTY - ISSUE_QTY
    FROM    MOVEMENTS;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Xong kỳ ' || P_PERIOD_YM || ' — tổng dòng: ' ||
        TO_CHAR(SQL%ROWCOUNT));
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'SP_BUILD_MONTHLY_STOCK_REPORT lỗi: ' || SQLERRM);
END;
